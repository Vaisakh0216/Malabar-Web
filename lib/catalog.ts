export function getBoutique(slug: string) {
  return boutiques.find((b) => b.slug === slug);
}

export function getCollection(slug: string) {
  return collections.find((c) => c.slug === slug);
}

export function getProduct(id: string) {
  return products.find((p) => p.id === id);
}

export function productsByBoutique(slug: string) {
  return products.filter((p) => p.boutique === slug);
}

export function productsInCollection(slug: string) {
  return products.filter((p) => p.collections.includes(slug));
}
